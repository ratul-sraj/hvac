// tools/make-sample-plan.mjs — build tests/samples/sample-plan.pdf, the PUBLIC sample drawing.
//
//   node tools/make-sample-plan.mjs            -> writes tests/samples/sample-plan.pdf
//   node tools/make-sample-plan.mjs --stdout   -> prints the summary only
//
// Why this file exists: LoadLens' original sample was a real client drawing (a 3-page, rotated
// ducting layout) and this repository is public, so it must never be referenced again. This tool
// writes a fully SYNTHETIC replacement with the same *shape* the parser and the tests expect:
//
//   * exactly 3 sheets (gf / l1 / l2), one level title per sheet
//   * room tags in the drawing format the real sheet used — NAME line(s), room NUMBER, then the
//     AREA with its unit, stacked top-to-bottom — so js/pdfparse.js reads them as source:"label"
//   * more than 120 room rows in total, with a mix of air-conditioned and excluded spaces
//     (toilets, stairs, stores, electrical, shafts, kitchen) and one ATRIUM of 1,249.3 m²
//   * no text, name, number or area taken from the private drawing — everything is invented
//
// It is dependency-free on purpose (raw PDF bytes, like tests/make-sample.mjs) and deterministic
// (seeded PRNG, no Math.random), so the committed fixture can always be regenerated byte-for-byte.
//
// Layout model (display coordinates, y down — exactly what js/pdfparse.js works in):
//   every tag is 3 stacked lines in one column:  NAME  /  NUMBER  /  AREA
//   the parser pairs a name/number with the first AREA *below* it, within 3.6·fontsize pt and
//   2.2·fontsize pt sideways, so each tag owns a 320 x 100 pt cell of its own: no tag can steal
//   another tag's lines, and no two lines ever share a y (so no accidental "schedule table" row).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const OUT_PATH = path.join(HERE, "..", "tests", "samples", "sample-plan.pdf");

// ---------------------------------------------------------------- geometry

const PAGE_W = 1700;   // pt — a wide sheet, like the A1 drawing this replaces
const PAGE_H = 1200;
const COLS = 5;
const COL_X = [80, 400, 720, 1040, 1360];
const ROW_Y = (row) => 120 + 100 * row;
const FONT = 10;       // tag font size
const SLOT = 16;       // line pitch inside a tag (name -> number -> area)
const NAME_FONT = 12;  // a two-line room name uses a slightly bigger face (more room upward)
const NAME_SLOT = 14;
const SUP2 = "\u00B2"; // m² — WinAnsi 0xB2

/** Tag at grid cell (row, col) -> the display coordinates it is drawn at. */
const cell = (index) => ({ row: Math.floor(index / COLS), col: index % COLS });

const AREA = (n, unit = "m" + SUP2) => `${n} ${unit}`;

// ---------------------------------------------------------------- deterministic PRNG

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// ---------------------------------------------------------------- the invented room mix

// [name, min m², max m², how many per floor]. Names use drawing abbreviations ("MEETING RM.",
// "ELEC. RM.") and never the words ROOM / NAME / SPACE / AREA / DESCRIPTION / FUNCTION standing
// alone — that keeps the parser's schedule-header heuristic from mistaking a tag row for a table.
const POOL = [
  ["OFFICE", 18, 85, 12],
  ["WORKSTATIONS", 60, 220, 2],
  ["MEETING RM.", 12, 45, 4],
  ["CONF. RM.", 20, 60, 2],
  ["TRAINING RM.", 30, 70, 1],
  ["MANAGER OFFICE", 15, 28, 3],
  ["CHIEF OFFICE", 18, 30, 2],
  ["DIRECTOR", 18, 28, 1],
  ["RECEPTION", 25, 120, 1],
  ["LOBBY", 15, 60, 1],
  ["COFFEE SHOP", 60, 170, 1],
  ["CAFETERIA", 50, 140, 1],
  ["SERVER RM.", 10, 30, 1],
  ["BMS", 6, 16, 1],
  ["SECURITY DESK", 6, 20, 1],
  ["FILING RM.", 12, 30, 2],
  ["MULTIPURPOSE HALL", 80, 130, 1],
  ["GYM", 60, 120, 1],
  ["CLINIC", 20, 40, 1],
  ["ARCH. RM.", 10, 30, 1],
  ["STORE 01", 8, 40, 2],
  ["ELEC. RM.", 6, 30, 2],
  ["M. TL.", 12, 30, 1],
  ["F. TL.", 12, 30, 1],
  ["FHC", 0.6, 1.5, 2],
  ["ST. 01", 14, 30, 1],
  ["KIT.", 3, 12, 1],
  ["PL 1", 3, 12, 1],
  ["IDF/TEL", 5, 20, 1],
];

const FLOOR_TITLES = ["GROUND FLOOR PLAN", "L1 FLOOR PLAN", "L2 FLOOR PLAN"];

/** One entry per tag: {name, area, number, lines?} — `lines` for a two-line room name. */
function floorRooms(floor) {
  const rand = mulberry32(0x5eed + floor * 7919);
  const specs = [];
  for (const [name, lo, hi, count] of POOL) {
    for (let k = 0; k < count; k++) {
      let area = Math.round((lo + rand() * (hi - lo)) * 10) / 10;
      specs.push({ name, area });
    }
  }
  // The three sheets must not be clones: rotate the mix and shift every area a little.
  const shift = floor * 13;
  const out = specs.map((s, i) => {
    const src = specs[(i + shift) % specs.length];
    return { name: src.name, area: src.area };
  });
  // Verbatim repeats of (name, area) inside one sheet would be dropped as duplicates, so nudge.
  const seen = new Set();
  for (const s of out) {
    while (seen.has(`${s.name}|${s.area}`)) s.area = Math.round((s.area + 0.1) * 10) / 10;
    seen.add(`${s.name}|${s.area}`);
  }
  return out;
}

// Fixed, hand-placed tags the tests and the "load sample" story rely on. They are PREPENDED to
// sheet 1's invented mix (never overwriting it), so their grid cells — and therefore their display
// coordinates in the text dump — are stable: index 0 -> (80, 120), index 1 -> (400, 120), ...
const FORCED = {
  0: [
    { name: "ATRIUM", area: "1,249.3" },
    { name: "MEETING RM.", area: 33.5 },
    { name: "ENTERTAINMENT &", lines: ["ENTERTAINMENT &", "RECREATION"], area: 115.4 },
  ],
};

/** All tags of one sheet, with coordinates, as flat text items. */
function floorItems(floor) {
  const rooms = [...(FORCED[floor] || []), ...floorRooms(floor)];

  const items = [];
  rooms.forEach((room, i) => {
    const { row, col } = cell(i);
    const x = COL_X[col];
    const y = ROW_Y(row);
    const number = String(floor * 100 + i + 1);
    if (room.lines) {
      // two-line room name: name lines, then number, then the area (bigger face -> more room)
      room.lines.forEach((line, k) =>
        items.push({ str: line, x, y: y + k * NAME_SLOT, size: NAME_FONT }));
      items.push({ str: number, x, y: y + room.lines.length * NAME_SLOT, size: NAME_FONT });
      items.push({ str: AREA(room.area), x, y: y + (room.lines.length + 1) * NAME_SLOT, size: NAME_FONT });
      return;
    }
    items.push({ str: room.name, x, y, size: FONT });
    items.push({ str: number, x, y: y + SLOT, size: FONT });
    items.push({ str: AREA(room.area), x, y: y + 2 * SLOT, size: FONT });
  });
  return { rooms, items };
}

// Sheet furniture: a level title (never a room name — it contains PLAN, which the parser rejects
// as a sheet annotation) plus a few duct/title-block labels that must never turn into rooms.
function floorFurniture(floor) {
  const items = [
    { str: FLOOR_TITLES[floor], x: 60, y: 46, size: 18 },
    { str: "SCALE 1:100", x: 60, y: 76, size: 8 },
    { str: "\u00F8175", x: 1430, y: 46, size: 8 },
    { str: "300 x 300 mm", x: 1430, y: 76, size: 8 },
  ];
  if (floor === 0) items.push({ str: "NOT ENCLOSED", x: 60, y: 1160, size: 8 });
  return items;
}

// ---------------------------------------------------------------- PDF writer

const esc = (s) =>
  String(s).replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");

function contentStream(items) {
  const out = ["BT"];
  for (const it of items) {
    out.push(`/F1 ${it.size} Tf`);
    out.push(`1 0 0 1 ${it.x} ${(PAGE_H - it.y).toFixed(2)} Tm (${esc(it.str)}) Tj`);
  }
  out.push("ET");
  return out.join("\n") + "\n";
}

/** @returns {{pdf: Buffer, items: Array, pages: number}} */
export function buildSamplePlan() {
  const perFloor = [0, 1, 2].map((floor) => {
    const { rooms, items } = floorItems(floor);
    return { floor, rooms, items: [...floorFurniture(floor), ...items] };
  });

  const streams = perFloor.map((f) => contentStream(f.items));
  const objs = [];
  objs[1] = "<< /Type /Catalog /Pages 2 0 R >>";
  objs[2] = "<< /Type /Pages /Kids [3 0 R 4 0 R 5 0 R] /Count 3 >>";
  [0, 1, 2].forEach((i) => {
    objs[3 + i] =
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] ` +
      `/Resources << /Font << /F1 9 0 R >> >> /Contents ${6 + i} 0 R >>`;
  });
  streams.forEach((s, i) => {
    objs[6 + i] = `<< /Length ${Buffer.byteLength(s, "latin1")} >>\nstream\n${s}endstream`;
  });
  // explicit widths for the whole WinAnsi range so pdf.js never needs standard-font metrics
  const widths = Array.from({ length: 224 }, () => 556).join(" ");
  objs[9] =
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding " +
    `/FirstChar 32 /LastChar 255 /Widths [${widths}] >>`;

  const chunks = [Buffer.from("%PDF-1.4\n%\xE2\xE3\xCF\xD3\n", "latin1")];
  let offset = chunks[0].length;
  const offsets = [0];
  for (let i = 1; i < objs.length; i++) {
    const body = Buffer.from(`${i} 0 obj\n${objs[i]}\nendobj\n`, "latin1");
    offsets[i] = offset;
    offset += body.length;
    chunks.push(body);
  }
  const xrefStart = offset;
  let xref = `xref\n0 ${objs.length}\n0000000000 65535 f \n`;
  for (let i = 1; i < objs.length; i++) xref += String(offsets[i]).padStart(10, "0") + " 00000 n \n";
  xref += `trailer\n<< /Size ${objs.length} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;
  chunks.push(Buffer.from(xref, "latin1"));

  return { pdf: Buffer.concat(chunks), pages: 3, rooms: perFloor.map((f) => f.rooms) };
}

export function writeSamplePlan(file = OUT_PATH) {
  const { pdf } = buildSamplePlan();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, pdf);
  return file;
}

function summary() {
  const { pdf, rooms } = buildSamplePlan();
  const lines = [
    `sample-plan.pdf: ${pdf.length} bytes, 3 pages`,
    ...rooms.map((r, i) => `  page ${i + 1}: ${r.length} room tags`),
    `  total: ${rooms.reduce((a, r) => a + r.length, 0)} room tags`,
  ];
  return lines.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes("--stdout")) {
    console.log(summary());
  } else {
    const file = writeSamplePlan();
    console.log("wrote " + file);
    console.log(summary());
  }
}
